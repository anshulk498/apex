package devadmin;

public class Pojo {
	
	private int id;
	private String name;
	private String role;
	
	public int getId() {
		return id;
	}
	
	public String getName() {
		return name;
	}
	
	public String getRole() {
		return role;
	}

	
	public void setId(int id) {
		this.id=id;
	}
	
	public void setName(String name) {
		this.name=name;
	}
	
	public void setRole(String role) {
		this.role=role;
	}
	
	
}
